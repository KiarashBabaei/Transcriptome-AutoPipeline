#!/usr/bin/env python3
"""GSE181294: source-filtered exploratory RI-PSI classification.

Input: SraRunTable.csv and RI_events_with_snoRNA.tsv from the existing upstream
analysis. This script DOES NOT validate how the PSI values were generated.

Primary task: Healthy vs Low-grade tumour vs High-grade tumour, according to
SRA metadata condition/grade (NOT a Gleason >=7 threshold).

Evaluation unit: BioSample, with Run PSI profiles averaged within BioSample.
Within-cohort nested 3-fold stratified cross-validation is exploratory only.
By default, only SRA records with LibrarySource=TRANSCRIPTOMIC are used,
matching the user-reported upstream exclusion of SINGLE CELL-labeled records.
The SRA label itself does not prove that the library was generated by bulk RNA-seq.
No comparison between LibrarySource groups is attempted after this exclusion.
"""
from __future__ import annotations

import argparse
import json
import platform
import warnings
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import sklearn
from sklearn.dummy import DummyClassifier
from sklearn.feature_selection import VarianceThreshold
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score, balanced_accuracy_score, classification_report,
    confusion_matrix, f1_score, roc_auc_score, roc_curve,
)
from sklearn.model_selection import GridSearchCV, StratifiedKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import LinearSVC

CLASSES = ["Healthy", "Low", "High"]
C_VALUES = [0.001, 0.01, 0.1, 1.0]
SEED = 42


def build_matrix(meta_path: Path, psi_path: Path, library_source: str):
    meta = pd.read_csv(meta_path, dtype={"Run": "string", "BioSample": "string"})
    raw = pd.read_csv(psi_path, sep="\t")
    required = {"Run", "BioSample", "condition", "grade", "BioProject", "LibrarySource"}
    absent = required.difference(meta.columns)
    if absent:
        raise ValueError(f"Metadata missing columns: {sorted(absent)}")
    if "eventID" not in raw.columns:
        raise ValueError("RI input missing eventID column")
    if not meta["BioProject"].dropna().eq("PRJNA751490").all():
        raise ValueError("Input has BioProject identifiers besides PRJNA751490 / GSE181294")
    if meta["Run"].duplicated().any():
        raise ValueError("Duplicate Run IDs in metadata")

    # Apply the upstream-design exclusion before constructing the ML matrix.
    # The PSI table may still carry columns for excluded SRA runs.
    all_rows = len(meta)
    excluded_source_rows = int(meta["LibrarySource"].ne(library_source).sum())
    meta = meta.loc[meta["LibrarySource"].eq(library_source)].copy()
    if meta.empty:
        raise ValueError(f"No records with LibrarySource={library_source!r}")

    labels = pd.Series(pd.NA, index=meta.index, dtype="string")
    labels.loc[meta["condition"].eq("Healthy")] = "Healthy"
    labels.loc[meta["condition"].eq("Tumor") & meta["grade"].eq("low_grade")] = "Low"
    labels.loc[meta["condition"].eq("Tumor") & meta["grade"].eq("high_grade")] = "High"
    meta = meta.assign(class_label=labels).dropna(subset=["class_label", "BioSample"])
    if meta.empty:
        raise ValueError("No three-class samples found")
    if (meta.groupby("BioSample")["class_label"].nunique() != 1).any():
        raise ValueError("Conflicting class labels within BioSample")
    if (meta.groupby("BioSample")["LibrarySource"].nunique() != 1).any():
        raise ValueError("Conflicting LibrarySource within BioSample")

    runs = meta["Run"].tolist()
    missing = sorted(set(runs) - set(raw.columns))
    if missing:
        raise ValueError(f"Missing {len(missing)} RNA-seq runs from PSI input: {missing[:10]}")
    raw[runs] = raw[runs].apply(pd.to_numeric, errors="coerce")
    # The same event can appear multiple times because of snoRNA overlaps.
    # The recorded PSI value of an event is combined by averaging duplicate rows.
    events = raw.groupby("eventID", sort=True)[runs].mean()
    if events.empty:
        raise ValueError("No RI events")
    invalid = (events.to_numpy() < -1e-6) | (events.to_numpy() > 1 + 1e-6)
    if np.any(invalid):
        raise ValueError("PSI includes values outside [0, 1]")

    runs_x_events = events.T.rename_axis("Run").reset_index()
    with_meta = runs_x_events.merge(
        meta[["Run", "BioSample", "class_label", "LibrarySource"]],
        on="Run", how="inner", validate="one_to_one"
    )
    X = with_meta.groupby("BioSample", sort=True)[events.index.tolist()].mean()
    by_sample = with_meta.groupby("BioSample", sort=True)
    y = by_sample["class_label"].first().reindex(X.index).astype(str)
    source = by_sample["LibrarySource"].first().reindex(X.index).astype(str)
    if y.value_counts().reindex(CLASSES, fill_value=0).min() < 3:
        raise ValueError("At least 3 independent BioSamples per class are needed")
    audit = {"metadata_runs_total": all_rows,
             "excluded_other_library_source_runs": excluded_source_rows,
             "selected_library_source": library_source}
    return X, y, source, len(meta), len(events), audit


def make_pipeline(model_name: str) -> Pipeline:
    estimator = (
        LogisticRegression(class_weight="balanced", max_iter=5000,
                           random_state=SEED)
        if model_name == "LogisticRegression"
        else LinearSVC(class_weight="balanced", max_iter=15000,
                       random_state=SEED)
    )
    return Pipeline([
        ("impute", SimpleImputer(strategy="median", keep_empty_features=True)),
        ("variance", VarianceThreshold(threshold=0.0)),
        ("scale", StandardScaler()),
        ("model", estimator),
    ])


def tune_and_fit(name, X_train, y_train):
    inner = StratifiedKFold(n_splits=3, shuffle=True, random_state=SEED)
    search = GridSearchCV(
        make_pipeline(name),
        {"model__C": C_VALUES},
        cv=inner,
        scoring="balanced_accuracy",
        error_score="raise",
        refit=True,
        n_jobs=1,
    )
    search.fit(X_train, y_train)
    return search


def score_metrics(truth, pred):
    return {
        "n_test": int(len(truth)),
        "accuracy": float(accuracy_score(truth, pred)),
        "balanced_accuracy": float(balanced_accuracy_score(truth, pred)),
        "macro_f1": float(f1_score(truth, pred, labels=CLASSES,
                                   average="macro", zero_division=0)),
    }


def run_nested_cv(X, y, name):
    outer = StratifiedKFold(n_splits=3, shuffle=True, random_state=SEED)
    pred = pd.Series(index=X.index, dtype="object")
    # Keep probabilities or OvR decision function scores for exploratory ROC.
    scores = pd.DataFrame(index=X.index, columns=CLASSES, dtype=float)
    fold_info = []
    for fold, (i_train, i_test) in enumerate(outer.split(X, y), 1):
        tr_idx, te_idx = X.index[i_train], X.index[i_test]
        if name == "Dummy":
            model = DummyClassifier(strategy="most_frequent")
            model.fit(X.loc[tr_idx], y.loc[tr_idx])
            output = model.predict(X.loc[te_idx])
            pred.loc[te_idx] = output
            # Constant majority-class score is not used for ROC AUC comparison.
            fold_info.append({"model": name, "fold": fold, "C": None,
                              "train_n": len(tr_idx), "test_n": len(te_idx)})
        else:
            search = tune_and_fit(name, X.loc[tr_idx], y.loc[tr_idx])
            model = search.best_estimator_
            pred.loc[te_idx] = model.predict(X.loc[te_idx])
            if name == "LogisticRegression":
                values = model.predict_proba(X.loc[te_idx])
            else:
                values = model.decision_function(X.loc[te_idx])
            scores.loc[te_idx, model.named_steps["model"].classes_] = values
            fold_info.append({"model": name, "fold": fold,
                              "C": float(search.best_params_["model__C"]),
                              "train_n": len(tr_idx), "test_n": len(te_idx)})
    return pred, scores, fold_info


def per_class_roc(truth, scores):
    aucs = {}
    for class_name in CLASSES:
        binary = (truth == class_name).astype(int)
        aucs[class_name] = float(roc_auc_score(binary, scores[class_name].to_numpy()))
    return aucs


def plot_cm(truth, pred, name, dst):
    cm = confusion_matrix(truth, pred, labels=CLASSES)
    fig, ax = plt.subplots(figsize=(6.6, 5.5))
    image = ax.imshow(cm, cmap="Blues")
    ax.set_xticks(range(3), CLASSES)
    ax.set_yticks(range(3), CLASSES)
    ax.set_xlabel("Predicted class")
    ax.set_ylabel("Actual class")
    ax.set_title(f"{name}: out-of-fold confusion matrix")
    for i in range(3):
        for j in range(3):
            ax.text(j, i, str(cm[i, j]), ha="center", va="center",
                    color="white" if cm[i, j] > cm.max() / 2 else "black")
    fig.colorbar(image, ax=ax, fraction=.046)
    fig.tight_layout()
    fig.savefig(dst, dpi=250)
    plt.close(fig)
    return cm.tolist()


def plot_roc(truth, scores, name, dst):
    fig, ax = plt.subplots(figsize=(6.8, 5.8))
    for class_name in CLASSES:
        positive = (truth == class_name).astype(int)
        fpr, tpr, _ = roc_curve(positive, scores[class_name])
        area = roc_auc_score(positive, scores[class_name])
        ax.plot(fpr, tpr, label=f"{class_name} (AUC={area:.3f})")
    ax.plot([0, 1], [0, 1], linestyle="--", color="grey")
    ax.set(xlabel="False positive rate", ylabel="True positive rate",
           title=f"{name}: pooled out-of-fold OvR ROC (exploratory)")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(dst, dpi=250)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", default="SraRunTable.csv", type=Path)
    parser.add_argument("--psi", default="RI_events_with_snoRNA.tsv", type=Path)
    parser.add_argument("--outdir", default="results_ml_bulk_filtered", type=Path)
    parser.add_argument("--library-source", default="TRANSCRIPTOMIC",
                        help="SRA LibrarySource value to retain (default TRANSCRIPTOMIC)")
    args = parser.parse_args()
    args.outdir.mkdir(parents=True, exist_ok=True)
    X, y, source, n_runs, n_events, audit = build_matrix(
        args.metadata, args.psi, args.library_source
    )
    print("LibrarySource filter:", audit)
    print("NOTE: LibrarySource metadata labels do not verify assay chemistry.")
    print(f"GSE181294 / PRJNA751490 | {n_runs} retained runs -> "
          f"{len(X)} BioSamples | {n_events} RI event features")
    print("Class distribution:", y.value_counts().to_dict())
    print("LibrarySource x class:\n", pd.crosstab(source, y).to_string())
    print(f"Missing PSI fraction: {X.isna().to_numpy().mean():.3f}")
    X.to_csv(args.outdir / "biosample_psi_features.csv")
    pd.DataFrame({"class_label": y, "LibrarySource": source}).to_csv(
        args.outdir / "biosample_metadata.csv"
    )

    preds = pd.DataFrame({"BioSample": X.index, "Actual": y.values,
                          "LibrarySource": source.values}, index=X.index)
    metrics = []
    fold_records = []
    for name in ["LogisticRegression", "LinearSVM", "Dummy"]:
        pred, scores, folds = run_nested_cv(X, y, name)
        fold_records.extend(folds)
        preds[name] = pred
        result = {"model": name, **score_metrics(y, pred)}
        result["confusion_matrix"] = plot_cm(
            y, pred, name, args.outdir / f"confusion_{name}.png"
        )
        if name != "Dummy":
            aucs = per_class_roc(y, scores)
            result["oof_ovr_auc_per_class"] = aucs
            result["oof_ovr_auc_macro"] = float(np.mean(list(aucs.values())))
            for cls in CLASSES:
                preds[f"{name}_score_{cls}"] = scores[cls]
            plot_roc(y, scores, name, args.outdir / f"roc_{name}.png")
        metrics.append(result)
        print(f"{name:20s} Accuracy={result['accuracy']:.3f} "
              f"BalancedAcc={result['balanced_accuracy']:.3f} "
              f"MacroF1={result['macro_f1']:.3f}")
        if name != "Dummy":
            print("  Exploratory pooled OOF OvR AUC:",
                  {k: round(v, 3) for k, v in aucs.items()})
        print(classification_report(y, pred, labels=CLASSES, zero_division=0))

    preds.to_csv(args.outdir / "oof_predictions.csv", index=False)
    pd.DataFrame(fold_records).to_csv(args.outdir / "fold_hyperparameters.csv", index=False)
    metadata = {
        "dataset": "GSE181294", "bioproject": "PRJNA751490",
        "target": "Three classes based on condition+grade: Healthy, Low, High",
        "evaluation_unit": "BioSample, NOT Run or verified patient",
        "runs": n_runs, "biosamples": len(X), "ri_features": n_events,
        "source_filter_audit": audit,
        "class_counts": y.value_counts().to_dict(),
        "missing_psi_fraction": float(X.isna().to_numpy().mean()),
        "n_cv_folds_outer": 3, "n_cv_folds_inner": 3,
        "random_state": SEED, "C_values": C_VALUES,
        "results": metrics,
        "environment": {"python": platform.python_version(),
                        "pandas": pd.__version__, "numpy": np.__version__,
                        "scikit_learn": sklearn.__version__},
        "interpretation_limits": [
            "Internal exploratory validation; not external or clinical validation",
            "Source PSI measurements taken as given, not re-validated here",
            "LibrarySource=TRANSCRIPTOMIC is an SRA metadata filter, not independently confirmed bulk protocol",
            "BioSample identifiers do not certify independence at patient level",
            "Cross-LibrarySource sensitivity was explored previously but excluded-source runs are absent here",
            "Pooled out-of-fold ROC scores come from models trained on differing folds",
            "Outcome selection and other exploratory analyses may introduce selection bias",
        ],
    }
    (args.outdir / "run_summary.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("\nSaved outputs under:", args.outdir.resolve())


if __name__ == "__main__":
    main()
